import secrets
import threading
import time
import uuid
from datetime import datetime, timezone

from sqlalchemy import DateTime, Uuid, func
from sqlalchemy.types import TypeDecorator
from sqlalchemy.orm import Mapped, mapped_column

_lock = threading.Lock()
_last_ms = 0
_counter = 0


def uuid7() -> uuid.UUID:
    """Time-ordered UUID (RFC 9562 version 7), monotonic within this process.

    48 bits of millisecond timestamp, then a 12-bit counter that increases for ids created
    in the same millisecond, then random bits. Sorting by id therefore matches creation
    order, which keeps "order by created_at, id" deterministic and index inserts local.
    """
    global _last_ms, _counter
    with _lock:
        ms = time.time_ns() // 1_000_000
        if ms > _last_ms:
            _last_ms, _counter = ms, 0
        else:
            _counter += 1
            if _counter > 0xFFF:
                _last_ms += 1
                _counter = 0
        ms, counter = _last_ms, _counter
    value = (
        (ms << 80) | (0x7 << 76) | (counter << 64) | (0b10 << 62) | secrets.randbits(62)
    )
    return uuid.UUID(int=value)


class UTCDateTime(TypeDecorator):
    """TIMESTAMPTZ that always comes back timezone-aware (UTC).

    PostgreSQL already does this; SQLite (used by the test suite) stores no zone and
    returns naive values, which then serialize without an offset. Same column type on
    PostgreSQL, so migrations are unaffected."""

    impl = DateTime(timezone=True)
    cache_ok = True

    def process_result_value(self, value, dialect):
        if value is not None and value.tzinfo is None:
            return value.replace(tzinfo=timezone.utc)
        return value


def utcnow() -> datetime:
    return datetime.now(timezone.utc)


class UUIDPrimaryKeyMixin:
    """UUID primary key generated by the application (UUIDv7)."""

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid7)


class TimestampMixin:
    """Timezone-aware created_at / updated_at.

    The ORM fills them with microsecond-precision UTC values; server_default=now() covers
    rows inserted by raw SQL.
    """

    created_at: Mapped[datetime] = mapped_column(
        UTCDateTime(), default=utcnow, server_default=func.now()
    )
    updated_at: Mapped[datetime] = mapped_column(
        UTCDateTime(),
        default=utcnow,
        onupdate=utcnow,
        server_default=func.now(),
    )
