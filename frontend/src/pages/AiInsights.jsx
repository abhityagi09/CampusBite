import { useEffect, useRef, useState } from "react";
import { Bot, ListChecks, Send } from "lucide-react";
import { errorMessage, statusOf } from "../api/client";
import { aiApi } from "../api/endpoints";
import { Button, PageHeader, Textarea } from "../components/ui";

const SUGGESTIONS = [
  "Summarize my last five orders.",
  "Which orders are still pending?",
  "How much did I spend this week?",
  "What dishes do I order most often?",
];

function friendlyError(err) {
  const s = statusOf(err);
  const wait = err?.response?.headers?.["retry-after"];
  if (s === 429) return `${errorMessage(err)}${wait ? ` (try again in ${wait}s)` : ""}`;
  if (s === 503) return errorMessage(err) || "AI insights are unavailable right now.";
  if (s === 504) return "The AI took too long to answer. Please try again.";
  return errorMessage(err);
}

/** Render the model's plain text safely: "- " bullets and **bold**, no HTML injection. */
function Formatted({ text }) {
  const inline = (line) => line.split(/(\*\*[^*]+\*\*)/g).map((part, i) =>
    part.startsWith("**") && part.endsWith("**") ? <strong key={i}>{part.slice(2, -2)}</strong> : part);
  const blocks = [];
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    const bullet = line.match(/^(?:[-*•]|\d+[.)])\s+(.*)$/);
    if (bullet) {
      const last = blocks[blocks.length - 1];
      if (last?.type === "ul") last.items.push(bullet[1]);
      else blocks.push({ type: "ul", items: [bullet[1]] });
    } else if (line) blocks.push({ type: "p", text: line.replace(/^#+\s*/, "") });
  }
  return blocks.map((b, i) => b.type === "ul"
    ? <ul key={i}>{b.items.map((t, j) => <li key={j}>{inline(t)}</li>)}</ul>
    : <p key={i}>{inline(b.text)}</p>);
}

/** Chat with the backend AI endpoint. Every answer shown came from POST /ai/insights. */
export function AiInsightsPage() {
  const [messages, setMessages] = useState([]); // {role: "me"|"ai"|"err", text, meta?}
  const [question, setQuestion] = useState("");
  const [busy, setBusy] = useState(false);
  const endRef = useRef(null);

  useEffect(() => endRef.current?.scrollIntoView?.({ behavior: "smooth", block: "end" }), [messages, busy]);

  const run = async (label, call) => {
    if (busy) return;
    setMessages((m) => [...m, { role: "me", text: label }]);
    setBusy(true);
    try {
      const res = await call();
      setMessages((m) => [...m, res.source === "no_orders"
        ? { role: "ai", text: res.answer, meta: "No orders yet – place one to get insights." }
        : { role: "ai", text: res.answer, meta: `AI-generated from your ${res.orders_considered} most recent order(s) · ${res.model}` }]);
    } catch (err) {
      setMessages((m) => [...m, { role: "err", text: friendlyError(err) }]);
    } finally {
      setBusy(false);
    }
  };
  const ask = (q) => {
    const text = q.trim();
    if (text.length < 3) return;
    setQuestion("");
    run(text, () => aiApi.ask(text));
  };

  return (
    <>
      <PageHeader title="AI order insights"
        subtitle="Ask about your own order history. Answers are generated by CampusBite's AI service from your orders only." />
      <div className="suggestions">
        <button type="button" disabled={busy} onClick={() => run("Summarize my order history.", aiApi.summary)}>
          <ListChecks size={14} /> Summarize my order history
        </button>
        {SUGGESTIONS.map((s) => <button key={s} type="button" disabled={busy} onClick={() => ask(s)}>{s}</button>)}
      </div>
      <div className="chat" aria-live="polite">
        {messages.length === 0 && (
          <div className="state"><Bot size={36} /><p className="muted">Pick a suggestion or type a question.</p></div>
        )}
        {messages.map((m, i) => (
          <div key={i} className={`bubble ${m.role}`}>
            {m.role === "ai" ? <Formatted text={m.text} /> : m.text}
            {m.meta && <div className="muted small" style={{ marginTop: 6 }}>{m.meta}</div>}
          </div>
        ))}
        {busy && <div className="bubble ai muted">Thinking…</div>}
        <div ref={endRef} />
      </div>
      <form className="chat-form" onSubmit={(e) => { e.preventDefault(); ask(question); }}>
        <Textarea name="question" aria-label="Your question" placeholder="e.g. Which restaurant did I order from most?"
          value={question} maxLength={500} rows={2} onChange={(e) => setQuestion(e.target.value)}
          onKeyDown={(e) => { if (e.key === "Enter" && !e.shiftKey) { e.preventDefault(); ask(question); } }} />
        <Button type="submit" loading={busy} disabled={question.trim().length < 3} aria-label="Send"><Send size={16} /></Button>
      </form>
    </>
  );
}
